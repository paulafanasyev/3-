export function formatEvent(key, params = {}) {
  const fn = Object.hasOwn(EVENTS, key) ? EVENTS[key] : null;
  return fn ? fn(params) : 'Событие в мире.';
}

export function errorText(code) {
  return (typeof code === 'string' && Object.hasOwn(ERRORS, code)) ? ERRORS[code] : 'Это действие сейчас невозможно';
}
